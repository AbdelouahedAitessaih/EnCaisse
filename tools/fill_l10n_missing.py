for loc, fname in locale_files.items():
    path = root / fname
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    for k, v in translations[loc].items():
        data[k] = v
    for mk, mv in meta.items():
        data[mk] = mv
    ordered = {"@@locale": data.get("@@locale", loc)}
    for k, v in data.items():
        if k == "@@locale":
            continue
        ordered[k] = v
    path.write_text(
        json.dumps(ordered, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"{fname}: +{len(translations[loc])} keys")

